/** The field types a store can define. Mirrors the server's FieldType enum. */
export type FieldType = 'STRING' | 'NUMBER' | 'BOOLEAN' | 'DATE' | 'ENUM';
export type EntityType = 'PRODUCT' | 'CATEGORY' | 'ORDER';
export type FieldValue = string | number | boolean;

/** Custom field types per entity. Generate a store's own with `shopos-sdk types`. */
export interface StoreFields {
  PRODUCT: Record<string, FieldValue>;
  CATEGORY: Record<string, FieldValue>;
  ORDER: Record<string, FieldValue>;
}

export interface CustomFieldDefinition {
  id: string;
  name: string;
  description?: string | null;
  fieldType: FieldType;
  entityType: EntityType;
  enumValues?: string[] | null;
  defaultValue?: string | null;
  isRequired: boolean;
}

/** Raw value as the API returns it. Values are stored as text on the server. */
export interface RawFieldValue {
  value: string;
  customField: { name: string; fieldType: FieldType };
}

/**
 * Converts a stored text value to its JavaScript type.
 * NUMBER -> number, BOOLEAN -> boolean, DATE/STRING/ENUM -> string.
 * Returns undefined for an empty value, or for text that does not match the type.
 */
export function parseFieldValue(
  fieldType: FieldType,
  text: string,
): FieldValue | undefined {
  if (text === '') return undefined;
  switch (fieldType) {
    case 'NUMBER': {
      const n = Number(text);
      return Number.isFinite(n) ? n : undefined;
    }
    case 'BOOLEAN':
      return text === 'true' ? true : text === 'false' ? false : undefined;
    default:
      return text;
  }
}

/** Turns the API's list of values into an object keyed by field name. */
export function toFieldObject<F>(values: RawFieldValue[] | null | undefined): Partial<F> {
  const out: Record<string, FieldValue> = {};
  for (const v of values ?? []) {
    const parsed = parseFieldValue(v.customField.fieldType, v.value);
    if (parsed !== undefined) out[v.customField.name] = parsed;
  }
  return out as Partial<F>;
}

const TS_TYPE: Record<FieldType, string> = {
  STRING: 'string',
  NUMBER: 'number',
  BOOLEAN: 'boolean',
  DATE: 'string',
  ENUM: 'string',
};

/**
 * Writes TypeScript types for a store's custom fields.
 * Every field is optional, because an existing record may have no value for it.
 */
export function generateFieldTypes(
  definitions: CustomFieldDefinition[],
  source = 'a ShopOS store',
): string {
  const entities: EntityType[] = ['PRODUCT', 'CATEGORY', 'ORDER'];
  const lines = [
    `// Generated by shopos-sdk from ${source.replace(/[\r\n]/g, ' ')}. Do not edit; run \`shopos-sdk types\` again.`,
    '',
    'export interface ShopFields {',
  ];
  for (const entity of entities) {
    const defs = definitions
      .filter((d) => d.entityType === entity)
      .sort((a, b) => a.name.localeCompare(b.name));
    lines.push(`  ${entity}: {`);
    for (const d of defs) {
      if (d.description) {
        lines.push(`    /** ${d.description.replace(/\*\//g, '*\\/').replace(/[\r\n]+/g, ' ')} */`);
      }
      const type =
        d.fieldType === 'ENUM' && d.enumValues?.length
          ? d.enumValues.map((v) => JSON.stringify(v)).join(' | ')
          : TS_TYPE[d.fieldType];
      lines.push(`    ${JSON.stringify(d.name)}?: ${type};`);
    }
    lines.push('  };');
  }
  lines.push('}', '');
  return lines.join('\n');
}
